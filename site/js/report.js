// "Save this reading": everything the results page said about a file, as a
// Markdown document to keep, attach to a ticket, or send to a colleague. The
// file's rows are not in it, only what was measured and recommended.
//
// Pure: the page passes in what it rendered, and tests/report.test.js checks
// the text.

const line = (text) => String(text ?? '').replace(/\s+/g, ' ').trim();
// Markdown table cells cannot hold a pipe, and a heading cannot start a cell.
const cell = (text) => line(text).replace(/\|/g, '\\|');

export function readingFileName(fileName = 'data.csv') {
  const stem = String(fileName).replace(/\.[^.]*$/, '').replace(/[^\w.-]+/g, '_').slice(0, 60) || 'data';
  return `dcn_reading_${stem}.md`;
}

// The document. `models`, `drifts` and `pipelines` are what the ranking
// functions returned; `notes` are the sentences the page showed above each list.
export function readingMarkdown({ T, sig, task, fileName, date, build = null, lead = null, leadText = '',
  models, drifts, pipelines, notes = {}, sentences = {}, checks = null }) {
  const taskLabel = T.TASKS.find(t => t.id === task)?.label ?? task;
  const codes = [...sig.codes, ...sig.flags];
  const out = [];

  out.push(`# Data Craft Nexus reading: ${line(fileName)}`, '');
  out.push(`Read on ${date}${build ? ` by the page built from commit ${build}` : ''}.`,
    `${sig.rows?.toLocaleString?.('en-US') ?? sig.rows} rows, ${sig.features} feature columns. `
    + `Target: ${sig.target ? `\`${line(sig.target)}\`` : 'none'}. Predicting: ${line(taskLabel).toLowerCase()}. `
    + `Row order ${sig.codes[1] === 'A22' ? 'matters' : 'does not matter'}.`, '');

  if (checks) {
    out.push('## Before you trust a score', '');
    if (checks.flags.length) {
      for (const f of checks.flags) {
        out.push(`- **${line(f.title)}.** ${line(f.text)} What to do: ${line(f.fix)}`
          + (f.measured ? ` Measured: ${line(f.measured)}` : ''));
      }
    } else {
      out.push(`Nothing found: ${checks.clear.map(line).join(', ')}.`);
    }
    out.push('');
  }

  out.push('## Signature', '', `\`${codes.join(' ')}\``, '', '| code | what it means |', '|---|---|');
  for (const code of codes) {
    const c = T.CODES[code];
    out.push(`| ${code} | ${cell(c ? `${c.name}: ${c.note}` : '')} |`);
  }
  out.push('');

  out.push('## Models', '');
  if (notes.models) out.push(line(notes.models), '');
  if (lead) out.push(`**Start here: ${lead.n}** (\`${lead.c}\`). ${line(leadText)}`, '');
  models.items.forEach((m, i) => {
    out.push(`${i + 1}. **${m.n}** (\`${m.c}\`)`
      + (m.evidenceScore != null ? `, evidence ${m.evidenceScore.toFixed(2)}` : '')
      + `, ${m.score} of ${m.of} coordinates matched.`);
    if (m.caution) out.push(`   Caution: ${line(m.caution)}.`);
    if (sentences[m.c]) out.push(`   Measured: ${line(sentences[m.c])}`);
    out.push(`   Watch for: ${line(m.fail)}`);
  });
  if (models.ruledOut?.length) {
    out.push('', 'Ruled out:', '');
    for (const m of models.ruledOut.slice(0, 12)) out.push(`- ${m.n} (\`${m.c}\`): ${line(m.why)}`);
    if (models.ruledOut.length > 12) out.push(`- and ${models.ruledOut.length - 12} more`);
  }
  out.push('');

  out.push('## Drift checkers', '');
  if (notes.drifts) out.push(line(notes.drifts), '');
  drifts.items.forEach((d, i) => {
    out.push(`${i + 1}. **${d.n}** (\`${d.c}\`). Threshold: ${line(d.thr)}`);
    if (sentences[d.c]) out.push(`   Measured: ${line(sentences[d.c])}`);
  });
  if (drifts.ruledOut?.length) {
    out.push('', 'Ruled out by how it will run:', '');
    for (const d of drifts.ruledOut) out.push(`- ${d.n} (\`${d.c}\`): ${line(d.why)}`);
  }
  out.push('');

  out.push('## Pipelines', '');
  pipelines.items.forEach((p, i) => out.push(`${i + 1}. **${p.n}** (\`${p.c}\`): stages ${p.stages.join(', ')}.`));
  out.push('');

  out.push('## Take it home', '',
    'The page can write a Python script that runs the shortlist on the whole file with the benchmark\'s '
    + 'preprocessing and cross-validation ("Download the script"), or run the same script in the browser '
    + '("Run it here").', '');
  out.push('---', '', 'Generated by Data Craft Nexus, https://aeternifrigus.github.io/Data-Craft-Nexus/. '
    + 'Every "measured" line comes from its published benchmark, on the evidence tab.', '');
  return out.join('\n');
}

export function downloadReading(text, name) {
  const url = URL.createObjectURL(new Blob([text], { type: 'text/markdown' }));
  const a = Object.assign(document.createElement('a'), { href: url, download: name });
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
