"""Run the page's own forecasting methods on real series, and record what each scored.

The take-home script forecasts a number from its own past with the methods the
page shows (site/js/export.js). This runs those same functions, generated by
the site's JavaScript and executed here, on series from public forecasting
collections, so what the page says about forecasting is measured rather than
assumed.

Every series is also measured the way the page measures an upload
(dcn/series.py): its period from the step between its dates, how often it is
zero, and how strongly it repeats and trends. forecast_learn.py then asks
whether those measurements should change which forecaster comes first.

What was fixed before any result existed is in bench/README.md, "Forecasting:
what the data has to show".

  python -m dcn.forecast --out results/forecast.csv
"""
from __future__ import annotations

import argparse
import csv
import io
import subprocess
import sys
import time
import warnings
import zipfile
from dataclasses import dataclass
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from .series import day_number, period_from_days, series_cell, series_features

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "bench" / "cache" / "forecast"

SEED = 0
PER_DATASET = 20        # series sampled from each collection
REFERENCE_SERIES = 0    # tuned boosting fits 150 models a series: see bench/README.md
MAX_LENGTH = 200        # the most recent values of a longer series
MIN_LENGTH = 20
CODES = ["TSM1", "TSM2", "TSM4", "TSM5"]   # the forecasting models the script can run

M4 = "https://raw.githubusercontent.com/Mcompetitions/M4-methods/master/Dataset/{part}/{freq}-{part_lower}.csv"
CRAN = "https://raw.githubusercontent.com/cran/{package}/master/data/{name}.rda"
M5 = "https://raw.githubusercontent.com/Nixtla/m5-forecasts/main/datasets/m5.zip"

# How each collection steps in time, as a pandas frequency, to write the dates
# the page would read.
PANDAS_FREQ = {"yearly": "YS", "quarterly": "QS", "monthly": "MS", "weekly": "W-MON", "daily": "D", "hourly": "h"}


@dataclass
class Collection:
    name: str
    unit: str        # datasets cut from one source share a unit and are counted once
    step: str        # yearly, quarterly, monthly, weekly, daily, hourly
    source: str
    note: str


COLLECTIONS = [
    Collection("m4_yearly", "m4_yearly", "yearly", "M4", "M4 competition, yearly series"),
    Collection("m4_quarterly", "m4_quarterly", "quarterly", "M4", "M4 competition, quarterly series"),
    Collection("m4_monthly", "m4_monthly", "monthly", "M4", "M4 competition, monthly series"),
    Collection("m4_weekly", "m4_weekly", "weekly", "M4", "M4 competition, weekly series"),
    Collection("m4_daily", "m4_daily", "daily", "M4", "M4 competition, daily series"),
    Collection("m4_hourly", "m4_hourly", "hourly", "M4", "M4 competition, hourly series"),
    Collection("carparts", "carparts", "monthly", "expsmooth",
               "monthly sales of car parts (Hyndman et al., 2008), complete series only"),
    Collection("pbs", "pbs", "monthly", "tsibbledata", "monthly Australian prescriptions, by concession, type and drug group"),
    Collection("aus_retail", "aus_retail", "monthly", "tsibbledata", "monthly Australian retail turnover, by state and industry"),
    Collection("aus_livestock", "aus_livestock", "monthly", "tsibbledata", "monthly Australian livestock slaughtered, by animal and state"),
    Collection("m5_items", "m5", "daily", "M5", "M5 competition, daily Walmart sales of one item in one store"),
    Collection("m5_store_departments", "m5", "daily", "M5", "M5 competition, the same sales summed by store and department"),
]
BY_NAME = {c.name: c for c in COLLECTIONS}


def fetch(url: str, name: str) -> Path:
    """Download once into the cache."""
    import urllib.request
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / name
    if not path.exists():
        with urllib.request.urlopen(url, timeout=600) as response:
            path.write_bytes(response.read())
    return path


def _m4(freq: str) -> dict[str, np.ndarray]:
    parts = []
    for part in ("Train", "Test"):
        path = fetch(M4.format(part=part, freq=freq, part_lower=part.lower()), f"m4-{freq}-{part.lower()}.csv")
        parts.append(pd.read_csv(path, index_col=0))
    train, test = (p.to_numpy(float) for p in parts)
    ids = parts[0].index.tolist()
    assert ids == parts[1].index.tolist(), "M4's train and test files list the same series in the same order"
    return {sid: np.r_[a[~np.isnan(a)], b[~np.isnan(b)]] for sid, a, b in zip(ids, train, test)}


def _rda(package: str, name: str) -> pd.DataFrame:
    import pyreadr
    return next(iter(pyreadr.read_r(str(fetch(CRAN.format(package=package, name=name), f"{name}.rda"))).values()))


def _panel(frame: pd.DataFrame, keys: list[str], time: str, value: str) -> dict[str, np.ndarray]:
    out = {}
    for key, group in frame.sort_values(time).groupby(keys):
        values = group[value].to_numpy(float)
        out["|".join(map(str, key if isinstance(key, tuple) else (key,)))] = values
    return out


def _m5() -> pd.DataFrame:
    path = fetch(M5, "m5.zip")
    with zipfile.ZipFile(path) as z:
        name = next(n for n in z.namelist() if n.endswith("sales_train_evaluation.csv"))
        return pd.read_csv(z.open(name))


def load(collection: Collection) -> dict[str, np.ndarray]:
    """Every series in a collection, oldest value first, with no gaps."""
    name = collection.name
    if name.startswith("m4_"):
        return _m4(collection.step.capitalize())
    if name == "carparts":
        frame = _rda("expsmooth", "carparts")
        return {str(c): frame[c].to_numpy(float) for c in frame.columns if frame[c].notna().all()}
    if name == "pbs":
        return _panel(_rda("tsibbledata", "PBS"), ["Concession", "Type", "ATC1", "ATC2"], "Month", "Scripts")
    if name == "aus_retail":
        return _panel(_rda("tsibbledata", "aus_retail"), ["Series ID"], "Month", "Turnover")
    if name == "aus_livestock":
        return _panel(_rda("tsibbledata", "aus_livestock"), ["Animal", "State"], "Month", "Count")
    if name.startswith("m5_"):
        sales = _m5()
        days = [c for c in sales.columns if c.startswith("d_")]
        if name == "m5_items":
            ids = sales["item_id"] + "|" + sales["store_id"]
            return dict(zip(ids, sales[days].to_numpy(float)))
        summed = sales.groupby(["store_id", "dept_id"])[days].sum()
        return {f"{s}|{d}": summed.loc[(s, d)].to_numpy(float) for s, d in summed.index}
    raise KeyError(name)


def usable(values: np.ndarray) -> bool:
    """Long enough, complete, and not flat: a series that never changes has nothing to forecast."""
    return len(values) >= MIN_LENGTH and np.isfinite(values).all() and np.ptp(values[-MAX_LENGTH:]) > 0


def sample(collection: Collection, per_dataset: int = PER_DATASET, seed: int = SEED) -> list[tuple[str, np.ndarray]]:
    """A seeded sample of a collection's usable series, each cut to its most recent MAX_LENGTH values."""
    series = {sid: v for sid, v in load(collection).items() if usable(v)}
    ids = sorted(series)
    rng = np.random.default_rng([seed, sum(map(ord, collection.name))])
    picked = sorted(rng.choice(ids, size=min(per_dataset, len(ids)), replace=False).tolist(), key=ids.index)
    return [(sid, series[sid][-MAX_LENGTH:]) for sid in picked]


def dates_for(step: str, n: int) -> list[str]:
    """The dates the page would read beside the values, in ISO form."""
    index = pd.date_range("2000-01-01", periods=n, freq=PANDAS_FREQ[step])
    return [d.strftime("%Y-%m-%d %H:%M") if step == "hourly" else d.strftime("%Y-%m-%d") for d in index]


def script_namespace() -> dict:
    """The take-home script the page writes for a forecast, generated by the site's JavaScript and loaded."""
    template = CACHE / "template.csv"
    CACHE.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(0)
    pd.DataFrame({"date": dates_for("daily", 60), "value": np.round(rng.normal(10, 1, 60), 3)}).to_csv(template, index=False)
    text = subprocess.run(["node", str(ROOT / "bench" / "tools" / "js_script.mjs"), str(template), "value", "forecast",
                           "A22", *CODES], capture_output=True, text=True, check=True, cwd=ROOT).stdout
    namespace = {"__name__": "dcn_shortlist"}
    exec(compile(text, "dcn_shortlist.py", "exec"), namespace)
    return namespace


FIELDS = ["dataset", "unit", "series", "n", "step", "period", "season", "zero_share", "adi", "cv2",
          "seasonal_strength", "trend_strength", "cell", "method", "status", "r2", "mae", "seconds", "detail"]

_NS: dict | None = None


def _init():
    global _NS
    warnings.simplefilter("ignore")
    _NS = script_namespace()


def run_series(job) -> list[dict]:
    """Every method on one series, in the script's own folds, scored by R² and by mean absolute error."""
    collection_name, sid, values, with_reference, skip = job
    collection = BY_NAME[collection_name]
    ns = _NS
    y = np.asarray(values, dtype=float)
    found = period_from_days([day_number(d) for d in dates_for(collection.step, len(y))])
    period = found[1] if found else None
    # The page's rule (series.js forecastSetup): a season when the dates give
    # one and the series holds two full cycles of it.
    season = period if period and period > 1 and len(y) >= 2 * period else None
    ns["SEASON"] = season
    features = series_features(y.tolist(), period)
    base = {"dataset": collection.name, "unit": collection.unit, "series": sid, "n": len(y), "step": collection.step,
            "period": period or "", "season": season or "", "cell": series_cell(features),
            **{k: round(float(features[k]), 6) if np.isfinite(features[k]) else "" for k in
               ("zero_share", "adi", "cv2", "seasonal_strength", "trend_strength")}}
    folds = ns["forecast_folds"](len(y))
    rows = []
    for code, name, needs, method in ns["forecast_runs"](y):
        if code in skip or (code == "BASE-HGB-TUNED" and not with_reference):
            continue
        row = {**base, "method": code}
        started = time.time()
        try:
            forecasts = ns["fold_forecasts"](y, folds, method)
            row.update(status="ok",
                       r2=float(np.mean([ns["r2_score"](y[test], f) for test, f in forecasts])),
                       mae=float(np.mean([ns["mean_absolute_error"](y[test], f) for test, f in forecasts])))
        except Exception as exc:  # a method that cannot handle a series is a result too
            row.update(status="error", detail=f"{type(exc).__name__}: {exc}"[:200])
        row["seconds"] = round(time.time() - started, 2)
        rows.append(row)
    return rows


def done(path: Path) -> dict[tuple[str, str], set[str]]:
    if not path.exists():
        return {}
    out: dict[tuple[str, str], set[str]] = {}
    with path.open() as fh:
        for row in csv.DictReader(fh):
            out.setdefault((row["dataset"], row["series"]), set()).add(row["method"])
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="results/forecast.csv")
    ap.add_argument("--collections", default="", help="comma-separated names (default: all)")
    ap.add_argument("--per-dataset", type=int, default=PER_DATASET)
    ap.add_argument("--reference", type=int, default=REFERENCE_SERIES)
    ap.add_argument("--jobs", type=int, default=2)
    args = ap.parse_args(argv)
    names = [n.strip() for n in args.collections.split(",") if n.strip()] or [c.name for c in COLLECTIONS]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    already = done(out)
    jobs = []
    for name in names:
        collection = BY_NAME[name]
        picked = sample(collection, args.per_dataset)
        print(f"{name}: {len(picked)} series", flush=True)
        for i, (sid, values) in enumerate(picked):
            skip = already.get((name, sid), set())
            with_reference = i < args.reference
            expected = {"NAIVE-LAST", "NAIVE-AVERAGE", *CODES} | ({"BASE-HGB-TUNED"} if with_reference else set())
            if expected <= skip:
                continue
            jobs.append((name, sid, values.tolist(), with_reference, skip))
    new_file = not out.exists()
    with out.open("a", newline="") as fh, Pool(args.jobs, initializer=_init) as pool:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        if new_file:
            writer.writeheader()
        for k, rows in enumerate(pool.imap_unordered(run_series, jobs), 1):
            writer.writerows(rows)
            fh.flush()
            if rows:
                print(f"[{k}/{len(jobs)}] {rows[0]['dataset']} {rows[0]['series']} ({rows[0]['cell']})", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
