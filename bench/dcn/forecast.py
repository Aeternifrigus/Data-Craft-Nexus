"""Run the page's own forecasting methods on real series, and record what each scored.

The take-home script forecasts a number from its own past with the methods the
page shows (site/js/export.js). This runs those same functions, generated by
the site's JavaScript and executed here, on series from public forecasting
collections, so what the page says about forecasting is measured rather than
assumed.

Every series is also measured the way the page measures an upload
(dcn/series.py): its period from the step between its dates, how often it is
zero, and how strongly it repeats and trends. forecast_learn.py then asks
whether those measurements should change which forecaster comes first.

What was fixed before any result existed is in bench/README.md, "Forecasting:
what the data has to show".

  python -m dcn.forecast --out results/forecast.csv
"""
